"""Generated device module dtx_devices (P8.14): devices of a draft, channels from the driver, files with header
and checksum, edited files, the CMakeLists line, prj.conf. Pure core, files live in tmp_path."""
from __future__ import annotations

import pytest

from dt_explorer.core import apply as apply_mod
from dt_explorer.core import codegen as cg
from dt_explorer.core.draft import Draft, DraftChild, DraftNode

DRIVER = """
static int other_channel_get_helper(int x);   /* prototype only: ignored */
static int xyz_channel_get(const struct device *dev, enum sensor_channel chan, struct sensor_value *val)
{
	switch (chan) {
	case SENSOR_CHAN_AMBIENT_TEMP:
		break;
	case SENSOR_CHAN_PRESS:
		if (chan == SENSOR_CHAN_HUMIDITY) { }
		break;
	default:
		return -ENOTSUP;
	}
	return 0;
}
static const struct sensor_driver_api api = { .channel_get = xyz_channel_get, };
"""


def make_draft() -> Draft:
    bus = DraftNode(cls="i2c", instance="sercom1", label="sercom1", compatible="atmel,sam0-i2c", children=[
        DraftChild(name="bme280", unit="76", compatible=["bosch,bme280"], labels=["bme280_76"]),
        DraftChild(name="nolabel", unit="50", compatible=["atmel,at24"]),
    ])
    leds = DraftNode(cls="gpio-leds", label="board_leds", compatible="gpio-leds", children=[
        DraftChild(name="led_0", labels=["led0"], props={}),
    ])
    return Draft(build="b", nodes=[bus, leds])


def make_app(tmp_path, cmake="project(x)\ntarget_sources(app PRIVATE src/main.c)"):
    app = tmp_path / "app"
    (app / "src").mkdir(parents=True)
    (app / "src" / "main.c").write_text("int main(void){return 0;}\n")
    (app / "CMakeLists.txt").write_text(cmake)                  # no trailing newline, as in the labs
    (app / "prj.conf").write_text("CONFIG_GPIO=y\n")
    return app


def test_channels_from_driver_reads_the_channel_get_body():
    assert cg.channels_from_driver([DRIVER]) == ["SENSOR_CHAN_AMBIENT_TEMP", "SENSOR_CHAN_PRESS", "SENSOR_CHAN_HUMIDITY"]
    assert cg.channels_from_driver(["static int f(void) { return 0; }"]) == []
    assert cg.channels_from_driver(["int g(void){ x = foo_channel_get(a); }\nint h(void){ SENSOR_CHAN_PRESS; }"]) == []


def test_real_bme280_driver_channels(rtos4_ws):
    src = rtos4_ws / "zephyr" / "drivers" / "sensor" / "bosch" / "bme280" / "bme280.c"
    if not src.is_file():
        pytest.skip(f"{src} missing")
    assert cg.channels_from_driver([src.read_text(encoding="utf-8", errors="ignore")]) == \
        ["SENSOR_CHAN_AMBIENT_TEMP", "SENSOR_CHAN_PRESS", "SENSOR_CHAN_HUMIDITY"]


def test_devices_from_draft_classes_and_notes():
    devs, notes = cg.devices_from_draft(make_draft(), lambda c: ["SENSOR_CHAN_PRESS"])
    assert [(d.ident, d.cls, d.compatible) for d in devs] == \
        [("bme280_76", "sensor", "bosch,bme280"), ("led0", "led", "gpio-leds")]
    assert devs[0].channels == ["SENSOR_CHAN_PRESS"] and devs[1].channels == []
    assert len(notes) == 1 and "nolabel@50 has no node label" in notes[0]


def test_rendered_files_have_header_and_checksum_and_api():
    devs, _ = cg.devices_from_draft(make_draft(), lambda c: ["SENSOR_CHAN_AMBIENT_TEMP", "SENSOR_CHAN_PRESS"])
    files = cg.render_files(devs)
    assert list(files) == ["CMakeLists.txt", "include/dtx_bme280_76.h", "include/dtx_devices.h", "include/dtx_led0.h",
                           "src/dtx_bme280_76.c", "src/dtx_devices.c", "src/dtx_led0.c"]
    for rel, text in files.items():
        assert "generated by dt_explorer (dtx_devices), checksum " in text.splitlines()[0], rel
        assert cg.header_state(text) == "intact", rel
    assert "int dtx_bme280_76_read(struct dtx_bme280_76_data *out)" in files["include/dtx_bme280_76.h"]
    assert "struct sensor_value ambient_temp;" in files["include/dtx_bme280_76.h"]
    c = files["src/dtx_bme280_76.c"]
    assert "DT_NODELABEL(bme280_76)" in c and "sensor_sample_fetch(dev)" in c
    assert "sensor_channel_get(dev, SENSOR_CHAN_PRESS, &out->press)" in c
    assert "int dtx_led0_set(bool on)" in files["include/dtx_led0.h"] and "GPIO_DT_SPEC_GET" in files["src/dtx_led0.c"]
    assert "dtx_bme280_76_init()" in files["src/dtx_devices.c"] and "dtx_led0_init()" in files["src/dtx_devices.c"]
    assert '#include "dtx_bme280_76.h"' in files["include/dtx_devices.h"]
    cm = files["CMakeLists.txt"]
    assert "target_include_directories(app PRIVATE include)" in cm and "src/dtx_bme280_76.c" in cm


def test_header_states():
    txt = cg.with_header("int x;\n", "c")
    assert cg.header_state(txt) == "intact"
    assert cg.header_state(txt.replace("int x;", "int y;")) == "edited"
    assert cg.header_state("int x;\n") == "foreign"
    assert cg.header_state(txt.replace("\n", "\r\n")) == "intact"          # CRLF from an editor is not an edit


def test_generate_edit_regenerate(tmp_path):
    app = make_app(tmp_path)
    devs, notes = cg.devices_from_draft(make_draft(), lambda c: ["SENSOR_CHAN_PRESS"])
    plan = cg.plan_generate(app, devs, notes)
    assert {f.state for f in plan.files} == {"new"}
    lines = cg.write_files(plan)
    assert len(lines) == 7 and all(ln.startswith("written:") for ln in lines)
    before = (app / "src" / "main.c").read_text()

    plan = cg.plan_generate(app, devs, notes)                              # nothing changed: all unchanged
    assert {f.state for f in plan.files} == {"unchanged"} and not any(f.writes for f in plan.files)

    # the user edits one file by hand
    mine = app / "dtx_devices" / "src" / "dtx_led0.c"
    mine.write_text(mine.read_text() + "/* my change */\n")
    # and the draft changes: another channel in the sensor
    devs[0].channels = ["SENSOR_CHAN_PRESS", "SENSOR_CHAN_HUMIDITY"]
    plan = cg.plan_generate(app, devs, notes)
    st = {f.rel: f.state for f in plan.files}
    assert st["src/dtx_led0.c"] == "edited" and st["include/dtx_bme280_76.h"] == "regenerate"
    assert st["include/dtx_led0.h"] == "unchanged"
    edited = next(f for f in plan.files if f.rel == "src/dtx_led0.c")
    assert "my change" in edited.diff and edited.diff.startswith("--- src/dtx_led0.c (on disk)")
    lines = cg.write_files(plan)
    assert any(ln.startswith("NOT written (edited)") and "dtx_led0.c" in ln for ln in lines)
    assert "/* my change */" in mine.read_text()                           # untouched
    assert "humidity" in (app / "dtx_devices" / "include" / "dtx_bme280_76.h").read_text()
    assert (app / "src" / "main.c").read_text() == before                  # src/ is never touched
    assert sorted(p.name for p in (app / "src").iterdir()) == ["main.c"]


def test_foreign_file_and_stale(tmp_path):
    app = make_app(tmp_path)
    devs, _ = cg.devices_from_draft(make_draft(), lambda c: [])
    cg.write_files(cg.plan_generate(app, devs))
    (app / "dtx_devices" / "CMakeLists.txt").write_text("# my own\n")      # no header at all
    plan = cg.plan_generate(app, devs[:1])                                 # the LED left the draft
    assert next(f for f in plan.files if f.rel == "CMakeLists.txt").state == "foreign"
    assert {p.name for p in plan.stale} == {"dtx_led0.h", "dtx_led0.c"}
    assert all(p.is_file() for p in plan.stale)                            # reported, not deleted
    cg.write_files(plan)
    assert (app / "dtx_devices" / "CMakeLists.txt").read_text() == "# my own\n"


def test_cmake_line_added_once_after_diff(tmp_path):
    app = make_app(tmp_path)
    devs, _ = cg.devices_from_draft(make_draft(), lambda c: [])
    plan = cg.plan_generate(app, devs)
    assert plan.cmake_state == "missing"
    assert plan.cmake_diff.count("\n+add_subdirectory(dtx_devices)") == 1
    assert "-target_sources(app PRIVATE src/main.c)" in plan.cmake_diff          # the old last line had no newline
    original = (app / "CMakeLists.txt").read_text()
    assert (app / "CMakeLists.txt").read_text() == original                      # planning wrote nothing
    assert "added" in cg.apply_cmake_line(plan)
    text = (app / "CMakeLists.txt").read_text()
    assert text == original + "\nadd_subdirectory(dtx_devices)\n"
    again = cg.plan_generate(app, devs)
    assert again.cmake_state == "present" and again.cmake_diff == ""
    assert "unchanged" in cg.apply_cmake_line(again)
    assert (app / "CMakeLists.txt").read_text() == text


def test_cmake_missing_cmakelists(tmp_path):
    app = make_app(tmp_path)
    (app / "CMakeLists.txt").unlink()
    plan = cg.plan_generate(app, [])
    assert plan.cmake_state == "no_cmakelists" and "nothing changed" in cg.apply_cmake_line(plan)


def test_prj_conf_block_appended_then_replaced(tmp_path):
    app = make_app(tmp_path)
    devs, _ = cg.devices_from_draft(make_draft(), lambda c: [])
    conf = "\n".join(["CONFIG_I2C=y", "CONFIG_BME280=y"] + cg.kconfig_for(devs)) + "\n"
    fp = apply_mod.plan_prj_conf(app, conf, today="2026-10-15")
    assert "+# dt_explorer codegen begin 2026-10-15" in fp.append_diff
    assert "CONFIG_GPIO=y" in fp.append_note or fp.append_note.startswith("1 line")        # already in prj.conf
    assert apply_mod.apply_prj_conf(fp).startswith("appended:")
    text = (app / "prj.conf").read_text()
    assert text.startswith("CONFIG_GPIO=y\n") and text.count("CONFIG_GPIO=y") == 1
    assert "CONFIG_SENSOR=y" in text and text.rstrip().endswith("# dt_explorer end")
    fp2 = apply_mod.plan_prj_conf(app, conf, today="2026-10-15")
    assert fp2.append_diff == "" and apply_mod.apply_prj_conf(fp2).startswith("skipped:")
    assert (app / "prj.conf").read_text() == text


def test_prj_conf_created_when_missing(tmp_path):
    app = make_app(tmp_path)
    (app / "prj.conf").unlink()
    fp = apply_mod.plan_prj_conf(app, "CONFIG_SENSOR=y\n")
    assert not fp.exists and apply_mod.apply_prj_conf(fp).startswith("written:")
    assert "CONFIG_SENSOR=y" in (app / "prj.conf").read_text()
